# ==============================================================================
# 1. ДІАГНОСТИЧНИЙ КАЛЬКУЛЯТОР
# ==============================================================================
with tab_calc:
    st.subheader("Введення клінічних даних пацієнта")
    st.caption("Відзначте симптоми, виявлені під час інструментального та клінічного огляду:")
    
    col1, col2 = st.columns(2)
    
    with col1:
        st.markdown("**Основні діагностичні маркери:**")
        lisch = st.checkbox(
            "Вузлики Ліша", 
            help="Пігментні гамартоми райдужки, які виявляють під час огляду щілинною лампою."
        )
        pseudo = st.checkbox(
            "Вроджений псевдоартроз", 
            help="Порушення остеогенезу довгих трубчастих кісток із формуванням несправжнього суглоба."
        )
        hyper = st.checkbox(
            "Артеріальна гіпертензія", 
            help="Стійке підвищення тиску (часто вторинного характеру внаслідок судинних уражень)."
        )
        leukemia = st.checkbox(
            "Мієлодиспластичний синдром / лейкемія", 
            help="Проліферативні зміни кровотворення, асоційовані з порушенням гена NF1."
        )
        
    with col2:
        st.markdown("**Додаткові соматичні прояви:**")
        delay = st.checkbox(
            "Затримка розвитку або мовлення", 
            help="Когнітивні труднощі, розлади концентрації або затримка психомоторного розвитку."
        )
        bone = st.checkbox(
            "Дисплазія кісток скелета", 
            help="Виражений сколіоз або характерна дисплазія кісток черепа."
        )
        cnf = st.checkbox(
            "Шкірні нейрофіброми", 
            help="Доброякісні пухлини оболонок нервів у товщі шкіри або підшкірно."
        )
        cals = st.checkbox(
            "Плями кольору «кава з молоком»", 
            help="Шість або більше гіперпігментованих плям характерного відтінку."
        )

    st.markdown("---")

    # Завантаження натренованої моделі
    @st.cache_resource
    def load_model():
        m = XGBClassifier()
        m.load_model("model_xgb.json")
        return m

    try:
        model = load_model()
    except Exception as err:
        st.error(f"Не вдалося завантажити файл моделі model_xgb.json: {err}")
        st.stop()

    if st.button("Розрахувати ймовірність", type="primary", use_container_width=True):
        feats = [
            int(lisch), int(pseudo), int(hyper), int(leukemia),
            int(delay), int(bone), int(cnf), int(cals)
        ]
        cols = [
            'Lisch_Nodules', 'Congenital_Pseudarthrosis', 'Hypertension', 
            'MDS_Leukemia', 'Developmental_Delay', 'Bone_Dysplasia', 
            'Cutaneous_Neurofibromas', 'Cafe_au_Lait_Spots'
        ]
        
        df_input = pd.DataFrame([feats], columns=cols)
        probs = model.predict_proba(df_input)[0]
        p_sporadic = probs[0] * 100
        p_familial = probs[1] * 100

        st.markdown("### Результат аналізу")
        
        r1, r2 = st.columns([1.2, 1.8])
        
        with r1:
            if p_familial >= 50.0:
                st.error(f"**Ймовірна сімейна форма**\n\nОцінка моделі: **{p_familial:.1f}%**")
                st.progress(int(p_familial))
            else:
                st.success(f"**Ймовірний спорадичний випадок**\n\nОцінка моделі: **{p_sporadic:.1f}%**")
                st.progress(int(p_sporadic))

            chart_df = pd.DataFrame({
                "Форма": ["Спорадична", "Сімейна"],
                "Ймовірність, %": [p_sporadic, p_familial]
            })
            st.bar_chart(chart_df.set_index("Форма"))

        with r2:
            st.markdown("**Клінічна інтерпретація:**")
            if p_familial >= 50.0:
                st.write(
                    "Поєднання введених симптомів частіше трапляється серед пацієнтів із підтвердженим сімейним анамнезом. "
                    "У такому разі рекомендовано провести ретельний огляд батьків і рідних братів або сестер (зокрема огляд очей "
                    "за допомогою щілинної лампи), контролювати артеріальний тиск та за потреби призначити молекулярно-генетичне тестування родини."
                )
            else:
                st.write(
                    "Клінічна картина більше відповідає первинній мутації, що виникла вперше в родоводі. "
                    "Для здорових батьків ризик повторного народження дитини з цією патологією залишається низьким. "
                    "Рекомендовано плановий диспансерний нагляд за дитиною та моніторинг опорно-рухового апарату."
                )

        st.caption(
            "Примітка: Розрахована ймовірність має консультативний характер і слугує алгоритмічною підказкою. "
            "Остаточний клінічний діагноз встановлює лікар-генетик."
        )

